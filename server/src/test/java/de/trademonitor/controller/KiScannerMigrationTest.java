package de.trademonitor.controller;

import static org.junit.jupiter.api.Assertions.*;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.transaction.support.TransactionTemplate;
import de.trademonitor.service.KiScannerSchemaMigration;

/** Real H2 schema/constraint/transaction tests; no production database. */
public class KiScannerMigrationTest {
    private JdbcTemplate database() {
        return new JdbcTemplate(new DriverManagerDataSource(
                "jdbc:h2:mem:migration_" + java.util.UUID.randomUUID() + ";DB_CLOSE_DELAY=-1", "sa", ""));
    }
    private KiScannerSchemaMigration migration(JdbcTemplate jdbc) {
        return new KiScannerSchemaMigration(jdbc,
                new TransactionTemplate(new DataSourceTransactionManager(jdbc.getDataSource())));
    }
    private void schema(JdbcTemplate jdbc, boolean broken) {
        jdbc.execute("CREATE TABLE ki_sync_runs (id BIGINT PRIMARY KEY, status VARCHAR(16), finished_at TIMESTAMP, note VARCHAR(1024))");
        jdbc.update("INSERT INTO ki_sync_runs (id,status) VALUES (1,'running')");
        jdbc.execute("CREATE TABLE ki_signals (id BIGINT PRIMARY KEY, signal_id BIGINT UNIQUE NOT NULL, name VARCHAR(255))");
        jdbc.execute("CREATE TABLE ki_documents (id BIGINT PRIMARY KEY, signal_id BIGINT, doc_key VARCHAR(512) UNIQUE, file_data BLOB)");
        jdbc.execute("CREATE TABLE ki_signals_v2 (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, signal_id BIGINT NOT NULL,"
                + "name VARCHAR(255), min_calmar_jahr DOUBLE, source_uid VARCHAR(255) NOT NULL, source_label VARCHAR(128), UNIQUE(source_uid,signal_id))");
        jdbc.execute("CREATE TABLE ki_documents_v2 (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, signal_id BIGINT,"
                + "doc_key VARCHAR(512) UNIQUE, " + (broken ? "" : "file_data BLOB,")
                + " source_uid VARCHAR(255), source_label VARCHAR(128))");
        jdbc.update("INSERT INTO ki_signals VALUES (1,7,'Original')");
        jdbc.update("INSERT INTO ki_documents VALUES (1,7,'signal/7/report.pdf',?)", "%PDF-original".getBytes());
        jdbc.update("INSERT INTO ki_documents VALUES (2,NULL,'portfolio/report.pdf',?)", "%PDF-portfolio".getBytes());
    }
    @Test void copiesLegacyWithoutRebindingAndOldUniqueConstraintCannotBlockCompositeRows() {
        JdbcTemplate jdbc = database(); schema(jdbc, false);
        KiScannerSchemaMigration migration = migration(jdbc); migration.afterPropertiesSet();
        assertNull(jdbc.queryForObject("SELECT min_calmar_jahr FROM ki_signals_v2", Double.class));
        assertEquals("legacy:v1", jdbc.queryForObject("SELECT source_uid FROM ki_signals_v2", String.class));
        assertEquals(1L, jdbc.queryForObject("SELECT id FROM ki_documents_v2 WHERE signal_id=7", Long.class));
        assertEquals("aborted", jdbc.queryForObject("SELECT status FROM ki_sync_runs", String.class));
        assertArrayEquals("%PDF-original".getBytes(), jdbc.queryForObject(
                "SELECT file_data FROM ki_documents_v2 WHERE signal_id=7", byte[].class));
        assertNull(jdbc.queryForObject("SELECT source_uid FROM ki_documents_v2 WHERE signal_id IS NULL", String.class));
        jdbc.update("INSERT INTO ki_signals_v2 (signal_id,name,source_uid,source_label) VALUES (7,'Other','source-b','B')");
        assertTrue(jdbc.queryForObject("SELECT id FROM ki_signals_v2 WHERE source_uid='source-b'", Long.class) > 1);
        assertEquals(2, jdbc.queryForObject("SELECT COUNT(*) FROM ki_signals_v2", Integer.class));
        migration.afterPropertiesSet();
        assertEquals(2, jdbc.queryForObject("SELECT COUNT(*) FROM ki_signals_v2", Integer.class));
        assertEquals("Original", jdbc.queryForObject("SELECT name FROM ki_signals", String.class));
        assertEquals(2, jdbc.queryForObject("SELECT COUNT(*) FROM ki_documents", Integer.class));
        assertFalse(migration.v2Active()); migration.activateV2(); assertTrue(migration.v2Active());
    }
    @Test void failedCopyRollsBackBothTablesAndLeavesOriginalsUnchanged() {
        JdbcTemplate jdbc = database(); schema(jdbc, true);
        assertThrows(RuntimeException.class, () -> migration(jdbc).afterPropertiesSet());
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM ki_signals_v2", Integer.class));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM ki_documents_v2", Integer.class));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM ki_scanner_protocol_state", Integer.class));
        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM ki_signals", Integer.class));
        assertEquals(2, jdbc.queryForObject("SELECT COUNT(*) FROM ki_documents", Integer.class));
    }
}
